    internal Func<string, bool> DownloadPermissionPrompt;

    async void OnDownloadPermission(object sender, CoreWebView2PermissionRequestedEventArgs e)
    {
        if (e.PermissionKind != CoreWebView2PermissionKind.MultipleAutomaticDownloads) return;
        var deferral = e.GetDeferral();
        try
        {
            string origin = new Uri(e.Uri).GetLeftPart(UriPartial.Authority);
            // Leave the WebView2 callback before displaying a modal dialog.
            await Task.Yield();
            bool allowed = approvedDownloadOrigins.Contains(origin) || (DownloadPermissionPrompt != null
                ? DownloadPermissionPrompt(origin)
                : MessageBox.Show(this, "האתר " + origin + " מבקש להוריד כמה קבצים. לאפשר הורדות ממנו במהלך השימוש הנוכחי?",
                    "הורדת קבצים", MessageBoxButtons.YesNo, MessageBoxIcon.Question) == DialogResult.Yes);
            if (allowed) approvedDownloadOrigins.Add(origin);
            e.SavesInProfile = false;
            e.State = allowed ? CoreWebView2PermissionState.Allow : CoreWebView2PermissionState.Deny;
        }
        catch { e.State = CoreWebView2PermissionState.Deny; }
        finally { deferral.Complete(); }
    }
    void SaveLectureCalendar(string course, Dictionary<string, object> message)
    {
        DateTime date;
        string first = Str(message, "first");
        var holidays = Str(message, "holidays").Split(new[] { ',', ' ', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
        foreach (string value in holidays.Concat(new[] { first }).Where(x => x.Length > 0))
            if (!DateTime.TryParseExact(value, "yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture,
                System.Globalization.DateTimeStyles.None, out date)) { Toast("הזן תאריכים בפורמט YYYY-MM-DD", true); return; }
        var meta = LoadMeta(course);
        meta["lectureCalendar"] = new { first = first, holidays = holidays };
        SaveMeta(course, meta); SendCourseLocal(course);
    }

    string LectureFingerprint(string course, int num)
    {
        var files = new List<string>();
        for (int i = 1; i <= num; i++)
        {
            string dir = LectureDir(course, i);
            if (Directory.Exists(dir)) files.AddRange(Directory.GetFiles(dir, "*", SearchOption.AllDirectories)
                .Where(f => !f.Contains("\\" + PointersFolder + "\\") && !IsSummaryFile(f) && Path.GetExtension(f).ToLowerInvariant() != ".mp4"));
        }
        // New exams/syllabus guidance change priorities even if lecture files stay the same.
        foreach (string area in new[] { Exams, CourseInfoFolder, General }) {
            string folder = Path.Combine(CourseDir(course), area);
            if (Directory.Exists(folder)) files.AddRange(Directory.GetFiles(folder, "*", SearchOption.AllDirectories)
                .Where(f => !f.Contains("\\" + SumitDir + "\\") && !Path.GetFileName(f).StartsWith(ExamPrepPage, StringComparison.OrdinalIgnoreCase)
                    && new[] { ".pdf", ".txt", ".md", ".docx", ".pptx" }.Contains(Path.GetExtension(f).ToLowerInvariant())));
        }
        using (var hash = System.Security.Cryptography.SHA256.Create())
        {
            // Hash source content, not generated pages, so a repeat request costs no AI tokens.
            var source = new System.Text.StringBuilder("lecture-v3|" + StudyPolicyVersion + "|");
            foreach (string file in files.OrderBy(f => f, StringComparer.OrdinalIgnoreCase))
                using (var stream = File.OpenRead(file)) source.Append(file).Append(Convert.ToBase64String(hash.ComputeHash(stream)));
            return Convert.ToBase64String(hash.ComputeHash(System.Text.Encoding.UTF8.GetBytes(source.ToString())));
        }
    }
    string SafeDownloadFolder(string folder)
    {
        folder = folder ?? "";
        // Only a lecture destination generated by our UI may contain path separators.
        var parts = folder.Replace('/', '\\').Split('\\');
        int number;
        if ((parts.Length == 2 || parts.Length == 3) && parts[0] == "הרצאות" && parts[1].StartsWith("הרצאה ")
            && int.TryParse(parts[1].Substring(6), out number) && number > 0 && number <= 200)
        {
            // "הרצאות\הרצאה N" or one of its own subfolders (homework, the lecturer's notes, the student's notebook).
            if (parts.Length == 3 && (parts[2] == Exercises || parts[2] == LecturerNotes || parts[2] == Notebook)) return Path.Combine(LectureFolderName(number), parts[2]);
            if (parts.Length == 2) return LectureFolderName(number);
        }
        return SafeName(folder.Length > 0 ? folder : Exams);
    }
    // Explicit student-owned lectures; Moodle sections are source categories, not lecture numbers.
    // A summary made by an earlier version sat in the lecture folder itself; it moves into the "סיכום הרצאה" folder.
    void MigrateOldSummary(string course, int num)
    {
        try
        {
            string dir = LectureDir(course, num);
            string oldHtml = Path.Combine(dir, SummaryName + ".html"), oldPdf = Path.Combine(dir, SummaryName + ".pdf");
            string oldDigest = Path.Combine(dir, ".תקציר.md"), oldPrint = Path.Combine(dir, ".summary-fingerprint");
            if (!File.Exists(oldHtml) && !File.Exists(oldPdf) && !File.Exists(oldDigest) && !File.Exists(oldPrint)) return;
            Action<string, string> move = (from, to) =>
            {
                if (!File.Exists(from) || File.Exists(to)) return;
                Directory.CreateDirectory(Path.GetDirectoryName(to));
                File.Move(from, to);
            };
            move(oldHtml, StudyPagePath(course, num));
            move(oldPdf, LecturePdfPath(course, num));
            move(oldDigest, Path.Combine(CourseDir(course), DigestRel(num).Replace('/', '\\')));
            move(oldPrint, Path.Combine(CourseDir(course), SumitDir, "fingerprints", num + ".txt"));
            HideSumit(course);
        }
        catch { }
    }

    List<object> ManualLectures(string course)
    {
        var meta = LoadMeta(course);
        var rows = meta.ContainsKey("lectures") ? meta["lectures"] as ArrayList : null;
        if (rows != null) foreach (var r in rows.Cast<Dictionary<string, object>>()) MigrateOldSummary(course, Int(r, "num"));
        return (rows ?? new ArrayList()).Cast<Dictionary<string, object>>()
            .OrderBy(x => Int(x, "num")).Select(x => (object)new {
                num = Int(x, "num"), title = Str(x, "title"), date = Str(x, "date"),
                summaryNotes = SummaryNotes(course, Int(x, "num")), formatOutdated = FormatOutdated(course, Int(x, "num")), due = Str(x, "due"), items = new object[0], local = LocalInfo(course, Int(x, "num")),
                // A summary that is being made keeps its progress when the student walks away and comes back.
                running = summaryRunning.Contains(course + "|" + Int(x, "num")) || summaryQueued.Contains(course + "|" + Int(x, "num")),
                progress = summaryProgress.ContainsKey(course + "|" + Int(x, "num")) ? summaryProgress[course + "|" + Int(x, "num")] : null
            }).ToList();
    }

    void SaveLecture(string course, Dictionary<string, object> message)
    {
        int num = Int(message, "num");
        if (string.IsNullOrWhiteSpace(course) || num < 1 || num > 200) { Toast("בחר מספר הרצאה בין 1 ל-200", true); return; }
        foreach (string field in new[] { "date", "due" })
        {
            DateTime parsed;
            string value = Str(message, field);
            if (value.Length > 0 && !DateTime.TryParseExact(value, "yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture,
                System.Globalization.DateTimeStyles.None, out parsed)) { Toast("תאריך לא תקין", true); return; }
        }
        var meta = LoadMeta(course);
        var rows = meta.ContainsKey("lectures") ? meta["lectures"] as ArrayList : null;
        rows = rows ?? new ArrayList();
        var row = rows.Cast<Dictionary<string, object>>().FirstOrDefault(x => Int(x, "num") == num);
        if (row == null) { row = new Dictionary<string, object>(); rows.Add(row); }
        row["num"] = num;
        row["title"] = Str(message, "title").Trim().Length > 0 ? Str(message, "title").Trim() : "הרצאה " + num;
        row["date"] = Str(message, "date"); row["due"] = Str(message, "due");
        meta["lectures"] = rows; meta["setupDone"] = true;
        foreach (string sub in new[] { LecturerNotes, Notebook, Exercises, RecordingFolder })
            Directory.CreateDirectory(Path.Combine(LectureDir(course, num), sub));
        SaveMeta(course, meta);
        SendCourseLocal(course);
    }

    // A link that wants a new window opens in the same view: the student stays in one place, and a download or a
    // Zoom recording page reached this way works like any other page.
    internal void OpenSitePopup(object sender, CoreWebView2NewWindowRequestedEventArgs e)
    {
        var core = sender as CoreWebView2;
        // The personal portal (and the pages it leads to) work like in a browser: a link that opens a window gets a real window, with its own
        // session link back to the page, so sign-in hand-offs and forms work. Everything else opens in the view the student is looking at.
        if (core != null && env != null && IsPortalPage(core.Source)) { OpenRealPopup(core, e); return; }
        Uri u;
        if (core != null && Uri.TryCreate(e.Uri, UriKind.Absolute, out u) && (u.Scheme == Uri.UriSchemeHttps || u.Scheme == Uri.UriSchemeHttp || u.Scheme == "blob"))
        { e.Handled = true; core.Navigate(e.Uri); return; }
        // Many pages open an empty window and set its address a moment later (window.open("") and then .location = ...). The page needs a real
        // window for that: a small hidden one is given, and whatever address it is sent to is opened in the view the student is looking at.
        if (core == null || env == null) { e.Handled = true; return; }
        var deferral = e.GetDeferral();
        var ctx = System.Threading.SynchronizationContext.Current;
        try
        {
            var holder = new Form { ShowInTaskbar = false, FormBorderStyle = FormBorderStyle.None, StartPosition = FormStartPosition.Manual, Location = new System.Drawing.Point(-32000, -32000), ClientSize = new System.Drawing.Size(10, 10) };
            var view = new Microsoft.Web.WebView2.WinForms.WebView2();
            holder.Controls.Add(view);
            holder.Show();
            Action closeLater = () => { if (ctx != null) ctx.Post(_ => { try { holder.Close(); } catch { } }, null); };
            view.EnsureCoreWebView2Async(env).ContinueWith(t =>
            {
                try
                {
                    var popupCore = view.CoreWebView2;
                    popupCore.NavigationStarting += (s2, e2) =>
                    {
                        if (Environment.GetEnvironmentVariable("SUMIT_DEBUG_POPUP") != null) Console.WriteLine("popup navigation: " + e2.Uri);
                        Uri target;
                        if (Uri.TryCreate(e2.Uri, UriKind.Absolute, out target) && (target.Scheme == Uri.UriSchemeHttps || target.Scheme == Uri.UriSchemeHttp))
                        { e2.Cancel = true; core.Navigate(e2.Uri); closeLater(); }
                    };
                    popupCore.NewWindowRequested += OpenSitePopup;
                    popupCore.DownloadStarting += OnSiteDownload; popupCore.PermissionRequested += OnDownloadPermission;
                    e.NewWindow = popupCore; e.Handled = true;
                    if (Environment.GetEnvironmentVariable("SUMIT_DEBUG_POPUP") != null) Console.WriteLine("popup window given");
                }
                catch { e.Handled = true; }
                finally { deferral.Complete(); }
                // A window that never goes anywhere is closed after a while.
                var closer = new System.Windows.Forms.Timer { Interval = 30000 };
                closer.Tick += delegate { closer.Stop(); try { holder.Close(); } catch { } };
                closer.Start();
            }, System.Threading.Tasks.TaskScheduler.FromCurrentSynchronizationContext());
        }
        catch { e.Handled = true; try { deferral.Complete(); } catch { } }
    }

    static bool IsPortalPage(string url)
    {
        Uri u;
        return Uri.TryCreate(url ?? "", UriKind.Absolute, out u) && (u.Host.Equals("portal.hit.ac.il", StringComparison.OrdinalIgnoreCase) || u.Host.Equals("webrashim.hit.ac.il", StringComparison.OrdinalIgnoreCase));
    }

    // The page the portal opens (the student information station, ...) appears in the same place as the other sites, not in a window of its own:
    // it still is the window the page asked for (so its sign-in hand-off works), but the files saved from it land in the timetable folder.
    WebView2 popupView;
    CoreWebView2 ActiveSiteCore() { return popupView != null && popupView.CoreWebView2 != null ? popupView.CoreWebView2 : (site != null ? site.CoreWebView2 : null); }
    void CloseSitePopup()
    {
        var pv = popupView; popupView = null;
        if (pv == null) return;
        try { sitePanel.Controls.Remove(pv); pv.Dispose(); } catch { }
        if (site != null) site.BringToFront();
    }
    void OpenRealPopup(CoreWebView2 opener, CoreWebView2NewWindowRequestedEventArgs e)
    {
        var deferral = e.GetDeferral();
        try
        {
            CloseSitePopup();
            var view = new Microsoft.Web.WebView2.WinForms.WebView2 { Dock = DockStyle.Fill };
            popupView = view;
            sitePanel.Controls.Add(view); view.BringToFront();
            view.EnsureCoreWebView2Async(env).ContinueWith(t =>
            {
                try
                {
                    var pc = view.CoreWebView2;
                    pc.NewWindowRequested += OpenSitePopup;
                    pc.DownloadStarting += OnSiteDownload; pc.PermissionRequested += OnDownloadPermission;
                    pc.SourceChanged += delegate { if (popupView == view) Send(new { type = "siteNav", url = pc.Source, canBack = pc.CanGoBack, canForward = pc.CanGoForward }); };
                    pc.NavigationStarting += delegate { Send(new { type = "siteLoading", loading = true }); };
                    pc.NavigationCompleted += delegate { Send(new { type = "siteLoading", loading = false }); };
                    pc.WindowCloseRequested += delegate { if (popupView == view) CloseSitePopup(); };
                    e.NewWindow = pc; e.Handled = true;
                }
                catch { e.Handled = true; CloseSitePopup(); }
                finally { deferral.Complete(); }
            }, System.Threading.Tasks.TaskScheduler.FromCurrentSynchronizationContext());
        }
        catch { e.Handled = true; try { deferral.Complete(); } catch { } }
    }    // ---------- Saving from the sites ----------

    // Where a file saved from a site goes: the course / lecture / folder chosen in the bar above the site, or "הורדות".
    string SiteSaveDir(string name, out string where)
    {
        string course = siteDownloadCourse;
        // Pages saved from the personal portal (timetable, exam board) go to the timetable folder, where "update timetable" reads them.
        var ac = ActiveSiteCore(); Uri au;
        if (course == null && ac != null && Uri.TryCreate(ac.Source ?? "", UriKind.Absolute, out au) && (au.Host.IndexOf("webrashim.hit.ac.il", StringComparison.OrdinalIgnoreCase) >= 0 || au.Host.IndexOf("cheesefork.cf", StringComparison.OrdinalIgnoreCase) >= 0))
        { where = "מערכת שעות"; return Path.Combine(AppRoot, TimetableFolder); }
        if (course == null) { where = "הורדות"; return Path.Combine(AppRoot, "הורדות"); }
        string rel = SafeDownloadFolder(siteDownloadFolder);
        string dir = Path.Combine(CourseDir(course), rel);
        string lecturesRoot = Path.Combine(CourseDir(course), "הרצאות") + "\\";
        // A lecture's own folder: slides go to the lecturer's notes, homework sheets to the homework.
        if (dir.StartsWith(lecturesRoot, StringComparison.OrdinalIgnoreCase) && dir.Substring(lecturesRoot.Length).IndexOf('\\') < 0) dir = LectureSubdir(dir, "", name);
        string tail = dir.Substring(CourseDir(course).Length).Trim('\\').Replace("הרצאות\\", "").Replace("\\", " › ");
        where = course + " › " + tail;
        return dir;
    }

    // "Save as PDF" from the bar: the page being shown is printed straight into the lecture the student is working on.
    async void SavePageAsPdf()
    {
        var c = ActiveSiteCore();
        if (c == null || env == null) return;
        try
        {
            string title = SafeName(string.IsNullOrWhiteSpace(c.DocumentTitle) ? "דף מהאתר" : c.DocumentTitle);
            string where;
            string dir = SiteSaveDir(title + ".pdf", out where);
            Directory.CreateDirectory(dir);
            string path = UniquePathIn(dir, title + ".pdf");
            Send(new { type = "siteDownload", name = Path.GetFileName(path), dir = dir, state = "started", where = where });
            var ps = env.CreatePrintSettings();
            ps.ShouldPrintBackgrounds = true; ps.ShouldPrintHeaderAndFooter = false;
            bool ok = await c.PrintToPdfAsync(path, ps);
            if (!ok || !File.Exists(path)) { Send(new { type = "siteDownload", name = Path.GetFileName(path), state = "failed" }); return; }
            Send(new { type = "siteDownload", name = Path.GetFileName(path), dir = dir, path = path, state = "done", where = where });
            if (siteDownloadCourse != null) SendCourseLocal(siteDownloadCourse);
        }
        catch (Exception ex) { Toast("לא הצלחתי לשמור כ-PDF: " + ex.Message, true); }
    }

    // "Update timetable" from the portal: the page on screen is saved by the app itself (text, picture and PDF), then everything saved is read.
    // The student only opens "מבנה יומן" / "לוח בחינות" and presses the button once on each.
    async void ImportFromPortal()
    {
        try
        {
            var c = ActiveSiteCore(); Uri au;
            bool onPortal = c != null && Uri.TryCreate(c.Source ?? "", UriKind.Absolute, out au) && (au.Host.IndexOf("webrashim.hit.ac.il", StringComparison.OrdinalIgnoreCase) >= 0 || au.Host.IndexOf("cheesefork", StringComparison.OrdinalIgnoreCase) >= 0);
            if (onPortal)
            {
                string dir = Path.Combine(AppRoot, TimetableFolder); Directory.CreateDirectory(dir);
                string text = "";
                try { text = json.Deserialize<string>(await c.ExecuteScriptAsync("(function(){var t=document.body?document.body.innerText:'';document.querySelectorAll('iframe').forEach(function(f){try{t+='\\n'+f.contentDocument.body.innerText}catch(e){}});return t})()")) ?? ""; } catch { }
                string title = c.DocumentTitle ?? "";
                string kind = System.Text.RegularExpressions.Regex.IsMatch(text + " " + title, "(לוח בחינות|בחינות|מועד א)") ? "לוח בחינות" : System.Text.RegularExpressions.Regex.IsMatch(text + " " + title, "(יומן|מערכת שעות|מערכת)") ? "מבנה יומן" : SafeName(string.IsNullOrWhiteSpace(title) ? "דף מהפורטל" : title);
                if (text.Trim().Length > 80) File.WriteAllText(Path.Combine(dir, kind + ".txt"), text, new System.Text.UTF8Encoding(true));
                try { var ps = env.CreatePrintSettings(); ps.ShouldPrintBackgrounds = true; ps.ShouldPrintHeaderAndFooter = false; await c.PrintToPdfAsync(Path.Combine(dir, kind + ".pdf"), ps); } catch { }
                try { using (var fs = File.Create(Path.Combine(dir, kind + ".png"))) await c.CapturePreviewAsync(CoreWebView2CapturePreviewImageFormat.Png, fs); } catch { }
                if (text.Trim().Length <= 80) Toast("הדף עוד ריק. פתח בפורטל את \"מבנה יומן\" או \"לוח בחינות\" ולחץ שוב", true);
            }
            ImportTimetable(null, true);
        }
        catch (Exception ex) { Toast("לא הצלחתי לשמור את הדף: " + ex.Message, true); }
    }

    static string UniquePathIn(string dir, string name)
    {
        string path = Path.Combine(dir, name);
        for (int i = 2; File.Exists(path); i++) path = Path.Combine(dir, Path.GetFileNameWithoutExtension(name) + " (" + i + ")" + Path.GetExtension(name));
        return path;
    }

    // A lecture summary (or any page of the course) shown inside the app, in the place where the sites appear.
    void ShowFile(Dictionary<string, object> m)
    {
        string path = Str(m, "path");
        if (path.Length == 0) return;
        string full = Path.GetFullPath(path), ext = Path.GetExtension(full).ToLowerInvariant();
        if (!(IsInside(full, StudyRoot) || IsInside(full, AppRoot)) || !File.Exists(full) || (ext != ".html" && ext != ".pdf")) return;
        if (ext == ".html") PrepareStudyPage(full);
        PlaceSite(m);
        site.CoreWebView2.Navigate(new Uri(full).AbsoluteUri);
        sitePanel.Visible = true;
        sitePanel.BringToFront();
    }

