    static string ImageToJpegBytesPath(string source, string target, int w, int h)
    {
        using (var img = System.Drawing.Image.FromFile(source))
        using (var bmp = new System.Drawing.Bitmap(w, h))
        using (var g = System.Drawing.Graphics.FromImage(bmp))
        {
            g.InterpolationMode = System.Drawing.Drawing2D.InterpolationMode.HighQualityBicubic;
            // Fill the box and crop the middle, like a cover image.
            double scale = Math.Max((double)w / img.Width, (double)h / img.Height);
            int sw = (int)Math.Ceiling(img.Width * scale), sh = (int)Math.Ceiling(img.Height * scale);
            g.DrawImage(img, (w - sw) / 2, (h - sh) / 2, sw, sh);
            Directory.CreateDirectory(Path.GetDirectoryName(target));
            bmp.Save(target, System.Drawing.Imaging.ImageFormat.Jpeg);
        }
        return target;
    }

    static string DataUrlOf(string file)
    {
        try { return File.Exists(file) ? "data:image/jpeg;base64," + Convert.ToBase64String(File.ReadAllBytes(file)) : ""; } catch { return ""; }
    }

