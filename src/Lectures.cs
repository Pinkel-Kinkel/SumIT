    string BackgroundFile(string course) { return Path.Combine(CourseDir(course), SumitDir, "background.jpg"); }

    // What the course shows behind its name: the student's picture, or a pair of colours. "" = the default.
    string BackgroundFor(string course)
    {
        var meta = LoadMeta(course);
        string img = DataUrlOf(BackgroundFile(course));
        if (img.Length > 0) return img;
        string c = Str(meta, "bgColor");
        return System.Text.RegularExpressions.Regex.IsMatch(c, "^#[0-9a-fA-F]{6},#[0-9a-fA-F]{6}$") ? c : "";
    }

    void SetCourseBackground(string course, string mode, string colors)
    {
        try
        {
            var meta = LoadMeta(course);
            if (mode == "image")
            {
                string f = PickImage("בחר תמונת רקע לקורס");
                if (f == null) return;
                ImageToJpegBytesPath(f, BackgroundFile(course), 900, 240);
                meta.Remove("bgColor");
            }
            else
            {
                if (File.Exists(BackgroundFile(course))) File.Delete(BackgroundFile(course));
                if (mode == "color" && System.Text.RegularExpressions.Regex.IsMatch(colors ?? "", "^#[0-9a-fA-F]{6},#[0-9a-fA-F]{6}$")) meta["bgColor"] = colors; else meta.Remove("bgColor");
            }
            SaveMeta(course, meta);
            HideSumit(course);
            SendCourseLocal(course);
            if (lastCourses != null) { foreach (var cc in lastCourses) if (Str(cc, "name") == course) cc["local"] = CourseLocal(course); Send(new { type = "courses", data = lastCourses }); }
        }
        catch (Exception ex) { Toast("לא הצלחתי לשנות את הרקע: " + ex.Message, true); }
    }

    // The app's helper folder is hidden, so the course folder shows only what the student cares about.
    void HideSumit(string course)
    {
        try
        {
            string d = Path.Combine(CourseDir(course), SumitDir);
            if (Directory.Exists(d)) File.SetAttributes(d, File.GetAttributes(d) | FileAttributes.Hidden);
        }
        catch { }
    }
